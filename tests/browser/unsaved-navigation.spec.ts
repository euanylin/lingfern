import { expect, test } from '@playwright/test';

test('unsaved reading notes survive cancelled Back, Forward and link navigation', async ({ page }) => {
  await page.goto('/library');
  await page.locator('.desktop-nav a[href="/today"]').click();
  await page.locator('.task-row').first().getByRole('button').click();
  await page.getByRole('dialog').locator('button[data-mode=practice]').click();
  await page.locator('.reading-notes summary').click();
  const note = page.locator('.reading-notes textarea'), destination = page.url();
  const id = destination.split('/').at(-1)!;
  await note.fill('Keep this unsaved reading note.');
  const owner = await page.evaluate(async id => (await (await import('/src/data/db.ts' as string)).sessions.get(id)).owner, id);
  let leave = false, confirmations = 0;
  page.on('dialog', async dialog => { expect(dialog.type()).toBe('confirm'); expect(dialog.message()).toBe('笔记尚未保存。仍要离开当前材料吗？'); confirmations++; if (leave) await dialog.accept(); else await dialog.dismiss(); });
  await page.evaluate(() => history.back());
  await expect.poll(() => confirmations).toBe(1);
  await expect(page).toHaveURL(destination);
  await expect(note).toHaveValue('Keep this unsaved reading note.');
  await page.evaluate(() => { history.back(); history.back(); });
  await expect.poll(() => confirmations).toBeGreaterThan(1);
  await expect(page).toHaveURL(destination);
  await expect(note).toHaveValue('Keep this unsaved reading note.');
  expect(await page.evaluate(async id => (await (await import('/src/data/db.ts' as string)).sessions.get(id)).owner, id)).toBe(owner);
  const beforeHeader = confirmations;
  await page.locator('.session-header a').click();
  await expect.poll(() => confirmations).toBe(beforeHeader + 1);
  await expect(page).toHaveURL(destination);
  await expect(note).toHaveValue('Keep this unsaved reading note.');
  // Exercise the shared link handler separately from the header's awaited release.
  await page.evaluate(() => { const link = document.createElement('a'); link.href = '/library'; link.textContent = 'Navigation regression'; document.querySelector('main')!.appendChild(link); });
  const beforeLink = confirmations;
  await page.getByRole('link', { name: 'Navigation regression' }).click();
  await expect.poll(() => confirmations).toBe(beforeLink + 1);
  await expect(page).toHaveURL(destination);
  await expect(note).toHaveValue('Keep this unsaved reading note.');
  leave = true;
  await page.evaluate(() => history.back());
  await expect(page).toHaveURL(/\/today$/);
  await page.evaluate(() => history.forward());
  await expect(page).toHaveURL(destination);
  await page.locator('.reading-notes summary').click();
  await expect(note).toHaveValue('');
  await page.locator('.session-header a').click();
  await expect(page).toHaveURL(/\/today$/);
  await page.evaluate(() => history.back());
  await expect(page).toHaveURL(destination);
  await page.locator('.reading-notes summary').click();
  await note.fill('Keep the forward-navigation draft.');
  leave = false;
  const beforeForward = confirmations;
  await page.evaluate(() => history.forward());
  await expect.poll(() => confirmations).toBe(beforeForward + 1);
  await expect(page).toHaveURL(destination);
  await expect(note).toHaveValue('Keep the forward-navigation draft.');
  leave = true;
  await page.evaluate(() => history.forward());
  await expect(page).toHaveURL(/\/today$/);
  await page.evaluate(() => history.back());
  await expect(page).toHaveURL(destination);
  await page.locator('.reading-notes summary').click();
  await expect(note).toHaveValue('');
});
