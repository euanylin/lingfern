import { confirmTask } from './task-start';
import { expect, test } from '@playwright/test';

test('A2 table preserves typed times and scores the exception on a new material', async ({ page }) => {
  await page.goto('/today');
  const task = page.locator('.task-row').filter({ has: page.getByRole('heading', { name: '核对开放时间的例外' }) });
  await task.getByRole('button', { name: '开始阅读' }).click();
  await confirmTask(page);
  await expect(page.getByRole('heading', { name: /Complete the opening-time table/ })).toBeVisible();
  await page.getByRole('textbox', { name: 'Friday' }).fill('eleven');
  await page.getByRole('textbox', { name: 'Wednesday' }).fill('nine');
  await expect(page.getByRole('button', { name: '保存答案' })).toBeEnabled();
  await page.getByRole('button', { name: '保存答案' }).click();
  await expect(page.getByRole('heading', { name: '✓ 回答正确' })).toBeVisible();
  await expect(page.locator('.feedback blockquote')).toHaveCount(2);
  await page.getByRole('button', { name: '下一题' }).click();
  await page.setViewportSize({ width: 320, height: 640 });
  await page.getByRole('heading', { name: /Which excerpt shows that visitors cannot enter/ }).focus();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'output/playwright/a2-evidence-320x640-light-zh-Hans-unselected.png', fullPage: true });
  const alternativeEvidence = page.getByRole('radio', { name: /A group planning a Friday visit/ });
  await alternativeEvidence.focus();
  await alternativeEvidence.press('Space');
  await page.getByRole('button', { name: '保存答案' }).click();
  await expect(page.getByRole('heading', { name: '✓ 回答正确' })).toBeVisible();
  await expect(page.locator('.feedback blockquote')).toHaveCount(2);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: '下一题' }).click();
  await expect(page.getByRole('textbox', { name: 'Thursday' })).toBeVisible();
  await page.getByRole('textbox', { name: 'Thursday' }).fill('12:00');
  await page.getByRole('textbox', { name: 'Tuesday' }).fill('10:00');
  await page.getByRole('button', { name: '保存答案' }).click();
  await expect(page.getByRole('heading', { name: '✓ 回答正确' })).toBeVisible();
  await expect(page.locator('.feedback blockquote')).toHaveCount(2);
  await page.screenshot({ path: 'output/playwright/a2-table-1440x900-light-zh-Hans-three-answers.png', fullPage: true });
  await page.getByRole('button', { name: '下一题' }).click();
  await expect(page.getByRole('button', { name: '保存答案' })).toBeDisabled();
  await page.getByRole('button', { name: '添加步骤: Check the usual opening days and times.' }).click();
  await page.getByRole('button', { name: '添加步骤: Plan to collect reserved materials after the doors open.' }).click();
  await page.getByRole('button', { name: "添加步骤: Check Thursday's changed opening time." }).click();
  const move = page.getByRole('button', { name: "上移: Check Thursday's changed opening time." });
  await move.focus();
  await move.press('Enter');
  await page.setViewportSize({ width: 320, height: 640 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('heading', { name: /Put the checks in a sensible order/ }).focus();
  await expect.poll(() => page.evaluate(() => document.querySelector('.question-panel h2')!.getBoundingClientRect().top >= document.querySelector('#root > header')!.getBoundingClientRect().bottom)).toBe(true);
  await page.screenshot({ path: 'output/playwright/a2-sequence-320x640-light-zh-Hans-three-selected.png' });
  await page.getByRole('button', { name: '保存答案' }).click();
  await expect(page.getByRole('heading', { name: '✓ 回答正确' })).toBeVisible();
  await expect(page.locator('.feedback')).toContainText("Check Thursday's changed opening time.");
  await expect(page.getByText('阅读任务已保存')).toBeVisible();
  await page.getByRole('link', { name: '返回今日' }).click();
  await page.goto('/progress');
  await page.locator('.history').filter({ has: page.getByRole('link', { name: /核对开放时间的例外/ }) }).locator('summary').click();
  await expect(page.getByText('Thursday: 12:00 · Tuesday: 10:00')).toBeVisible();
});

test('A2 table draft returns after leaving the task', async ({ page }) => {
  await page.goto('/today');
  const task = page.locator('.task-row').filter({ has: page.getByRole('heading', { name: '核对开放时间的例外' }) });
  await task.getByRole('button', { name: '开始阅读' }).click();
  await confirmTask(page);
  await page.getByRole('textbox', { name: 'Friday' }).fill('11 am');
  await page.waitForTimeout(500); // wait for the 350 ms local draft debounce
  await page.getByRole('link', { name: '离开任务' }).click();
  await expect(page).toHaveURL(/\/today$/);
  await page.getByRole('link', { name: '今日', exact: true }).click();
  await task.getByRole('button', { name: '继续任务' }).click();
  await confirmTask(page);
  await expect(page.getByRole('textbox', { name: 'Friday' })).toHaveValue('11 am');
  await expect(page.getByRole('textbox', { name: 'Wednesday' })).toHaveValue('');
});

test('a partly ordered A2 response survives leaving and reopening', async ({ page }) => {
  await page.goto('/today');
  const task = page.locator('.task-row').filter({ has: page.getByRole('heading', { name: '核对开放时间的例外' }) });
  await task.getByRole('button', { name: '开始阅读' }).click();
  await confirmTask(page);
  await page.getByRole('textbox', { name: 'Friday' }).fill('11:00');
  await page.getByRole('textbox', { name: 'Wednesday' }).fill('9:00');
  await page.getByRole('button', { name: '保存答案' }).click();
  await page.getByRole('button', { name: '下一题' }).click();
  await page.locator('input[type=radio]').nth(1).check();
  await page.getByRole('button', { name: '保存答案' }).click();
  await page.getByRole('button', { name: '下一题' }).click();
  await page.getByRole('textbox', { name: 'Thursday' }).fill('12:00');
  await page.getByRole('textbox', { name: 'Tuesday' }).fill('10:00');
  await page.getByRole('button', { name: '保存答案' }).click();
  await page.getByRole('button', { name: '下一题' }).click();
  await page.getByRole('button', { name: '添加步骤: Check the usual opening days and times.' }).click();
  await page.getByRole('button', { name: "添加步骤: Check Thursday's changed opening time." }).click();
  await page.waitForTimeout(500);
  await page.getByRole('link', { name: '离开任务' }).click();
  await page.goto('/today');
  await task.getByRole('button', { name: '继续任务' }).click();
  await confirmTask(page);
  await expect(page.locator('.sequence-order li')).toHaveCount(2);
  await expect(page.getByRole('button', { name: '保存答案' })).toBeDisabled();
  await page.getByRole('button', { name: '添加步骤: Plan to collect reserved materials after the doors open.' }).click();
  await page.getByRole('button', { name: '保存答案' }).click();
  await expect(page.getByRole('heading', { name: '✓ 回答正确' })).toBeVisible();
});
