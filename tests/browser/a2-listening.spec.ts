import { confirmTask } from './task-start';
import { expect, test } from '@playwright/test';

test('A2 change notices play locally and save evidence after complete playback', async ({ page, context }) => {
  const external: string[] = [];
  await context.route('**/*', route => {
    const url = route.request().url();
    if (!url.startsWith('http://127.0.0.1:5173/')) { external.push(url); return route.abort(); }
    return route.continue();
  });
  await page.goto('/today');
  const task = page.locator('.task-row').filter({ has: page.getByRole('heading', { name: '听懂临时变动' }) });
  await task.getByRole('button', { name: '开始听力' }).click();
  await confirmTask(page);
  await expect(page.locator('.session-meta')).toHaveCount(0);
  await expect(page.locator('.session-title')).toBeVisible();
  await expect(page.locator('.question-number bdi')).toHaveText(/1 \/ \d+/);
  await expect(page.locator('.passage')).toHaveCount(0);
  const completion = page.getByRole('textbox', { name: '填写听到的缺失内容。' });
  await completion.fill('Room 12');
  await expect(page.getByRole('button', { name: '保存答案' })).toBeDisabled();
  await page.waitForTimeout(500);
  await page.getByRole('link', { name: '离开任务' }).click();
  await page.getByRole('link', { name: '今日', exact: true }).click();
  await task.getByRole('button', { name: '继续任务' }).click();
  await confirmTask(page);
  await expect(completion).toHaveValue('Room 12');
  await page.getByRole('button', { name: '播放 / 重听' }).click();
  await expect.poll(() => page.locator('audio').evaluate((audio: HTMLAudioElement) => Number.isFinite(audio.duration) && audio.duration > 20)).toBe(true);
  await page.locator('audio').evaluate((audio: HTMLAudioElement) => { audio.muted = true; audio.currentTime = audio.duration - 0.15; });
  await expect.poll(() => page.locator('audio').evaluate((audio: HTMLAudioElement) => audio.ended)).toBe(true);
  await expect(page.getByRole('button', { name: '保存答案' })).toBeDisabled();
  await page.locator('audio').evaluate((audio: HTMLAudioElement) => { audio.playbackRate = 16; });
  await page.getByRole('button', { name: '播放 / 重听' }).click();
  await page.locator('audio').evaluate((audio: HTMLAudioElement) => { audio.currentTime = 0; });
  await expect(page.getByText('录音已播放，可以选择并保存。', { exact: true })).toBeVisible({ timeout: 20_000 });
  await page.getByRole('button', { name: '保存答案' }).click();
  await expect(page.getByRole('heading', { name: '✓ 回答正确' })).toBeVisible();
  await expect(page.locator('.feedback blockquote')).toContainText('Room Twelve');
  await page.screenshot({ path: 'output/playwright/a2-listening-1440x900-light-zh-Hans-one-answer.png', fullPage: true });
  await page.getByRole('link', { name: '离开任务' }).click();
  await expect(page).toHaveURL(/\/today$/);
  await page.getByRole('link', { name: '今日', exact: true }).click();
  await task.getByRole('button', { name: '继续任务' }).click();
  await confirmTask(page);
  await expect(page.locator('.feedback blockquote')).toContainText('Room Twelve');
  await page.getByRole('button', { name: '下一题' }).click();
  await expect(page.getByRole('heading', { name: 'What do you need to bring?' })).toBeVisible();
  await page.locator('input[type=radio]').nth(0).check();
  await expect(page.locator('input[type=radio]').nth(0)).toBeChecked();
  await page.getByRole('button', { name: '保存答案' }).click();
  await expect(page.getByText('播放请求次数: 0', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '下一题' }).click();
  await page.locator('input[type=radio]').nth(1).check();
  await expect(page.getByRole('button', { name: '保存答案' })).toBeDisabled();
  const seen = await page.evaluate(async () => (await import('/src/data/db.ts' as string)).exposures.toArray());
  expect(seen).toHaveLength(1);
  expect(seen[0].contacts).toHaveLength(2);
  expect(new Set(seen[0].contacts.map((contact: { questionId: string }) => contact.questionId)).size).toBe(2);
  expect(external).toEqual([]);
});
