// Generates the offline fallback lexicon used by the syntax-tree tagger when no dictionary lookup is
// available. The lists are derived from the installed Open English WordNet buckets, so they are
// reproducible rather than hand-maintained: run `node scripts/tree-lexicon.mjs` after the dictionary
// changes and commit the result. A word only reaches a list by its entry in the dictionary itself,
// never because one test sentence needed it.
//
// The inclusion rule is a natural guess without context: a part of speech qualifies when it is the
// word's dominant reading and that reading has at least two senses. That keeps "letter" (noun 5,
// verb 3) a noun, "wooden" (adjective 2) an adjective and "way" (noun 12, adverb 1) a noun, while a
// word whose senses are evenly split keeps both readings. Counting senses alone is not enough: it
// made "way" an adverb and broke "in what way does it matter".
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { lemmaCandidates } from '../src/shared/wordnet-pos.ts';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const dictionary = new URL('public/dictionary/oewn-2025/', root);
const target = new URL('src/shared/tree-lexicon.ts', root);

// A part of speech has to be common enough to be a natural guess. Nouns and verbs are the open
// classes with the most entries, so they need more senses; adjectives and adverbs are smaller and
// a two- or three-sense adjective such as "wooden" is still the natural reading.
const minimumSenses = { noun: 3, verb: 3, adjective: 3, adverb: 3 };
const parts = ['noun', 'verb', 'adjective', 'adverb'];

const frames = JSON.parse(readFileSync(new URL('content/tree-clause-frames.json', root), 'utf8'));
assert.equal(frames.sourceSha256, '7d749f6e2c39e6970e4997839dcf6e42fd281f3c2fae0171d2192bae8cfa4b51');
const clauseLemmas = new Set(Object.keys(frames.verbs));
for (const [word, senses] of Object.entries(frames.verbs)) {
  assert(/^[a-z]+$/u.test(word) && Array.isArray(senses) && senses.length > 0);
  assert(senses.every(sense => sense.id.startsWith(`${word}%2:`) && sense.frames.length > 0 && sense.frames.every(frame => ['via-that', 'nonreferential-sent'].includes(frame))));
}
assert.equal(frames.objectInfinitiveFrame, 'vtaa-to-inf');
const objectLemmas = new Set(Object.keys(frames.objectInfinitives));
for (const [word, senses] of Object.entries(frames.objectInfinitives)) {
  assert(/^[a-z]+$/u.test(word) && senses.length > 0 && senses.every(sense => sense.startsWith(`${word}%2:`)));
}
const objectWords = new Set(objectLemmas);
const forms = JSON.parse(readFileSync(new URL('forms.json', dictionary), 'utf8'));
const verbReadings = [];
const clauseWords = new Set(clauseLemmas);
for (const [word, lemmas] of Object.entries(forms)) {
  if (!/^[a-z]+$/u.test(word)) continue;
  if (lemmas.some(lemma => clauseLemmas.has(lemma))) clauseWords.add(word);
  if (lemmas.some(lemma => objectLemmas.has(lemma))) objectWords.add(word);
}
const buckets = readdirSync(dictionary).filter(name => /^pos-[a-z0-9]\.json$/u.test(name)).sort();
const lists = Object.fromEntries(parts.map(part => [part, []]));
for (const name of buckets) {
  const data = JSON.parse(readFileSync(new URL(name, dictionary), 'utf8'));
  for (const [word, packed] of Object.entries(data)) {
    // Only plain lowercase letters can match a token; a headword with punctuation or a space never
    // equals a single word, and quoting it verbatim would break the emitted module.
    if (!/^[a-z]+$/u.test(word)) continue;
    const counts = { noun: packed & 15, verb: (packed >> 4) & 15, adjective: (packed >> 8) & 15, adverb: (packed >> 12) & 15 };
    if (counts.verb) verbReadings.push(word);
    if (counts.verb) {
      const lemmas = [word, ...lemmaCandidates(word, forms, 'verb')];
      if (lemmas.some(lemma => clauseLemmas.has(lemma))) clauseWords.add(word);
      if (lemmas.some(lemma => objectLemmas.has(lemma))) objectWords.add(word);
    }
    const best = Math.max(...Object.values(counts));
    for (const part of parts) if (counts[part] === best && counts[part] >= minimumSenses[part]) lists[part].push(word);
  }
}
const sorted = Object.fromEntries(parts.map(part => [part, lists[part].sort()]));

const clauses = [...clauseWords].sort();
assert([...clauseLemmas].every(lemma => clauseWords.has(lemma)), 'Missing source clause lemma');
const objectInfinitives = [...objectWords].sort();
const fingerprint = createHash('sha256').update(JSON.stringify({ ...sorted, clauses, objectInfinitives, verbReadings: verbReadings.sort() })).digest('hex').slice(0, 16);
const header = `// Generated by scripts/tree-lexicon.mjs from public/dictionary/oewn-2025/. Do not edit by hand.
// Fingerprint: ${fingerprint}
// Source: Open English WordNet 2025, CC BY 4.0 (see dictionary/oewn-2025/README.md).
// Rule: a part of speech is listed for a word when it is that word's dominant reading and has at
// least ${parts.map(part => `${minimumSenses[part]} ${part} senses`).join(', ')}.
// Possible verb readings retain dictionary evidence for contextual tagging when offline.
// Clause and object-infinitive selectors derive from source verb frames in content/tree-clause-frames.json.
// Regenerate rather than extending a list by hand.
`;
const body = Object.entries(sorted)
  .concat([['finiteClauseVerb', clauses], ['objectInfinitiveVerb', objectInfinitives], ['verbReading', verbReadings.sort()]])
  .map(([part, list]) => {
    const label = part[0].toUpperCase() + part.slice(1);
    const name = part.endsWith('Verb') ? part + 's' : part === 'verbReading' ? 'fallbackVerbReadings' : `fallback${label}s`;
    const chunks = [];
    // Each chunk ends with a space so concatenating neighbouring chunks keeps the separator.
    for (let index = 0; index < list.length; index += 10) chunks.push(`  '${list.slice(index, index + 10).join(' ')} '`);
    return `export const ${name} = new Set((\n${chunks.join(' +\n')}\n).split(' '));`;
  })
  .join('\n\n');

const output = `${header}\n${body}\n`;
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== output) {
    console.error('tree-lexicon: src/shared/tree-lexicon.ts is stale; run node scripts/tree-lexicon.mjs');
    process.exit(1);
  }
  console.log(`tree-lexicon: up to date (${parts.map(part => `${part} ${sorted[part].length}`).join(', ')})`);
} else {
  writeFileSync(target, output);
  console.log(`tree-lexicon: ${parts.map(part => `${part} ${sorted[part].length}`).join(', ')}`);
}
